def make_handler(results_dir: Path):
    json_file = results_dir / "test_report.json"
    txt_file = results_dir / "test_report.txt"

    class ReportHandler(BaseHTTPRequestHandler):
        def log_message(self, format: str, *args: Any) -> None:
            # Keep terminal output clean while retaining startup info
            pass

        def _send_bytes(self, status: int, content_type: str, data: bytes, extra_headers: Optional[Dict[str, str]] = None) -> None:
            self.send_response(status)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store, no-cache, must-revalidate")
            if extra_headers:
                for k, v in extra_headers.items():
                    self.send_header(k, v)
            self.end_headers()
            self.wfile.write(data)

        def do_GET(self) -> None:
            parsed = urlparse(self.path)
            path = parsed.path

            if path == "/" or path == "/index.html":
                data, err = load_report_data(json_file)
                html_doc = build_dashboard_html(data, err)
                self._send_bytes(HTTPStatus.OK, "text/html; charset=utf-8", html_doc.encode("utf-8"))
                return

            if path == "/api/report":
                data, err = load_report_data(json_file)
                status = HTTPStatus.OK if err is None else HTTPStatus.NOT_FOUND
                payload = json.dumps({"ok": err is None, "data": data, "error": err}).encode("utf-8")
                self._send_bytes(status, "application/json; charset=utf-8", payload)
                return

            if path in ("/view/json", "/download/json"):
                if not json_file.exists():
                    self._send_bytes(
                        HTTPStatus.NOT_FOUND,
                        "text/plain; charset=utf-8",
                        f"test_report.json not found at {json_file}\n".encode("utf-8"),
                    )
                    return
                raw = json_file.read_bytes()
                headers = {"Content-Disposition": 'attachment; filename="test_report.json"'} if path.startswith("/download") else None
                self._send_bytes(HTTPStatus.OK, "application/json; charset=utf-8", raw, headers)
                return

            if path in ("/view/txt", "/download/txt"):
                if not txt_file.exists():
                    self._send_bytes(
                        HTTPStatus.NOT_FOUND,
                        "text/plain; charset=utf-8",
                        f"test_report.txt not found at {txt_file}\n".encode("utf-8"),
                    )
                    return
                raw = txt_file.read_bytes()
                headers = {"Content-Disposition": 'attachment; filename="test_report.txt"'} if path.startswith("/download") else None
                self._send_bytes(HTTPStatus.OK, "text/plain; charset=utf-8", raw, headers)
                return

            self._send_bytes(HTTPStatus.NOT_FOUND, "text/plain; charset=utf-8", b"Not Found\n")

    return ReportHandler


def main() -> int:
    parser = argparse.ArgumentParser(description="API Sentinel Unit Test Report Web Dashboard")
    parser.add_argument("--host", default="127.0.0.1", help="Bind host (default: 127.0.0.1)")
    parser.add_argument("--port", type=int, default=8765, help="Bind port (default: 8765)")
    parser.add_argument(
        "--results-dir",
        type=Path,
        default=DEFAULT_RESULTS_DIR,
        help="Directory containing test_report.json and test_report.txt",
    )
    parser.add_argument("--no-browser", action="store_true", help="Do not auto-open browser tab")
    args = parser.parse_args()

    handler_cls = make_handler(args.results_dir)
    ThreadingHTTPServer.allow_reuse_address = True
    server = ThreadingHTTPServer((args.host, args.port), handler_cls)
    url = f"http://{args.host}:{args.port}"

    print("=" * 68)
    print("API Sentinel — Unit Test Report Web Dashboard")
    print("=" * 68)
    print(f"Dashboard URL : {url}")
    print(f"Report Source : {args.results_dir / 'test_report.json'}")
    print("Press Ctrl+C to stop the server.")
    print("=" * 68)

    if not args.no_browser:
        threading.Timer(0.4, lambda: webbrowser.open(url)).start()

    def handle_sig(signum, frame):
        raise KeyboardInterrupt()

    signal.signal(signal.SIGTERM, handle_sig)

    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nShutting down report dashboard server.")
    finally:
        server.server_close()

    return 0


if __name__ == "__main__":
    sys.exit(main())
