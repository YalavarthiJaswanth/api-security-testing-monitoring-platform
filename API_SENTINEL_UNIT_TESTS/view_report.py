def load_report_data(json_path: Path) -> Tuple[Optional[Dict[str, Any]], Optional[str]]:
    """Read and validate test_report.json without hardcoding fallback counts."""
    if not json_path.exists():
        return None, f"Report file not found at {json_path}. Run 'python3 run_tests.py' first to generate test results."
    try:
        raw = json_path.read_text(encoding="utf-8")
        data = json.loads(raw)
        if not isinstance(data, dict) or "summary" not in data or "suites" not in data:
            return None, f"Report file at {json_path} is missing required 'summary' or 'suites' sections."
        return data, None
    except json.JSONDecodeError as exc:
        return None, f"Invalid JSON in {json_path}: {exc}"
    except OSError as exc:
        return None, f"Unable to read {json_path}: {exc}"


